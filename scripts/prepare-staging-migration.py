#!/usr/bin/env python3
"""Generate SQL-Editor-compatible schema-only migration from the verified Docker schema."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
sql = (root / 'db/migrations/02-business.sql').read_text()
sql = re.sub(r'^\\(?:un)?restrict .*\n', '', sql, flags=re.M)
sql = re.sub(r'^SET (?:transaction_timeout|row_security) = .*;\n', '', sql, flags=re.M)
sql = re.sub(r'^ALTER .* OWNER TO .*;\n', '', sql, flags=re.M)
sql = sql[:sql.index('-- Name: DEFAULT PRIVILEGES FOR SEQUENCES;')]
sql = sql.replace('GRANT USAGE ON SCHEMA private TO authenticated;', '''REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA private TO authenticated;''')
prefix = '''-- Generated by scripts/prepare-staging-migration.py; run only in empty pactfit-staging.
-- No data import, role initialization, or auth schema modification.
BEGIN;
DO $$ BEGIN
  IF to_regprocedure('auth.uid()') IS NULL THEN
    RAISE EXCEPTION 'Managed Supabase auth.uid() is required';
  END IF;
  IF to_regclass('public.profiles') IS NOT NULL THEN
    RAISE EXCEPTION 'Business schema already exists; refusing bootstrap';
  END IF;
END $$;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated;
'''
suffix = '''
REVOKE ALL ON SCHEMA migration FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA migration, private FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA migration, private FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA private TO authenticated;
GRANT EXECUTE ON FUNCTION private.is_space_member(text), private.my_space_ids() TO authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
ALTER TABLE private.rate_hits ENABLE ROW LEVEL SECURITY;
ALTER TABLE migration.action_log ENABLE ROW LEVEL SECURITY;
SET check_function_bodies = true;
NOTIFY pgrst, 'reload schema';
COMMIT;
'''
(root / 'staging/migrations/001-business.sql').write_text(prefix + sql + suffix)
